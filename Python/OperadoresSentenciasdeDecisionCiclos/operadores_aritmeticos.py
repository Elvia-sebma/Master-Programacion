print('***Operadores Aritmeticos***')
a,b =10,5
print(f'valor inicial a: {a}')
print(f'Valor inicial b : {b}')

#operador de suma +
resultado =a + b
print(f'Resultado operador suma a + b es:{resultado}')

#operador de resta -
resultado = a - b
print (f'Resultador operador resta a - b es:{resultado}')

#Operador de multiplicacion *
resultado = a * b
print(f'Resultado de operador multiplicacion a * b es:{resultado}')

#Operador de divicion /
resultado = a / b
print(f'Resultado de operador divicion a * b es: {resultado}')

#Operador de modulo (residuo de la division)%
resultado = a % b
print(f'Resultado del operador modulo a % b es:{resultado}')

#Operador exponente (potencia)
resultado = 2** 3 #base2, exponente :3 =2*2*2*=8

print(f'Resultado del operador exponente 2 ** 3 es:{resultado}')

