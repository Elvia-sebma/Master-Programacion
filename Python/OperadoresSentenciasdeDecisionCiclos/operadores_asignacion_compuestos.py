print('*** Operadores de Asignacion Compuesto ***')
a, b = 10, 15
print(f'valor inicial de a = {a}')
print(f'valor inicial de b = {b}')

#Operador compuesto de suma += (suma con asignacion)
a += b #a = a+b
print(f' Resultado del operador a+= es: {a}')

#Operador compuesto de resta -=
a = 10
a-= b #a = a - b
print(f'Resultado del operador a-= es : {a}')

#Operador compuesto de multiplicacion*=
a = 10
a *= b # a= a*b
print(f'Resultado del operador a *=  b es :{a}')

#Operador compuesto de division /=
a=10
a/=b #a=a/b
print(f'Resultador del operador a/= b es:{a}')


